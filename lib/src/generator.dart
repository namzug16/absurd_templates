import 'diagnostic.dart';
import 'template.dart';

final _classNamePattern = RegExp(r'^[A-Za-z][A-Za-z0-9]*$');
final _wordSeparatorPattern = RegExp(r'[^A-Za-z0-9]+');
final _memberNamePattern = RegExp(r'^[a-z][A-Za-z0-9]*$');

const _fragmentSource = r'''
/// Composable HTML returned by every fragment function; render it with [toHtml].
final class Fragment {
  const Fragment._(this._render);

  final void Function(StringBuffer) _render;

  String toHtml() {
    final out = StringBuffer();
    _render(out);
    return out.toString();
  }
}

/// Writes fragments as HTML, iterables item by item, and every other non-null
/// value as escaped text.
void _$write(StringBuffer out, Object? value) {
  if (value is Fragment) {
    value._render(out);
  } else if (value is Iterable) {
    for (final item in value) {
      _$write(out, item);
    }
  } else if (value != null) {
    _$writeEscaped(out, value.toString());
  }
}

// Names an HTML parser reads as one attribute name.
final _$attributeNamePattern = RegExp('^[^\\s"\'<>/=\\x00-\\x1F\\x7F]+\$');

/// Writes each entry of [attributes] as ` name="value"`, failing on names
/// that are not valid HTML or already in [writtenNames], the names in the
/// tag so far, which it adds to.
void _$writeAttributes(
  StringBuffer out,
  Map<String, String>? attributes,
  Set<String> writtenNames,
) {
  if (attributes == null) return;
  for (final MapEntry(key: name, :value) in attributes.entries) {
    if (!_$attributeNamePattern.hasMatch(name)) {
      throw ArgumentError.value(
        name,
        'attributes',
        'is not a valid HTML attribute name',
      );
    }
    if (!writtenNames.add(name.toLowerCase())) {
      throw ArgumentError.value(
        name,
        'attributes',
        'is already an attribute of this tag and browsers keep only the '
            'first; compute one value in Dart and pass it in',
      );
    }
    out
      ..write(' ')
      ..write(name)
      ..write('="');
    _$writeEscaped(out, value);
    out.write('"');
  }
}

/// Writes [text] with &, <, >, " and ' replaced by the same entities as
/// dart:convert's HtmlEscape, which is several times slower.
void _$writeEscaped(StringBuffer out, String text) {
  var unwrittenStart = 0;
  for (var index = 0; index < text.length; index++) {
    final entity = switch (text.codeUnitAt(index)) {
      0x26 => '&amp;',
      0x3C => '&lt;',
      0x3E => '&gt;',
      0x22 => '&quot;',
      0x27 => '&#39;',
      _ => null,
    };
    if (entity == null) continue;
    out
      ..write(text.substring(unwrittenStart, index))
      ..write(entity);
    unwrittenStart = index + 1;
  }
  out.write(unwrittenStart == 0 ? text : text.substring(unwrittenStart));
}
''';

/// First line of every generated file; abs only overwrites files that
/// start with it.
const generatedFileHeader =
    '// GENERATED by abs (Absurd Templates). DO NOT EDIT.';

final class _Namespace {
  _Namespace(this.className, this.accessPath);

  final String className;

  /// How Dart code reaches this namespace, such as `Html.pages`.
  final String accessPath;
  final sourcePathByMemberName = <String, String>{};
  final templatePathByMethodName = <String, String>{};
  final compiledTemplateByMethodName = <String, CompiledTemplate>{};
  final namespaceByGetterName = <String, _Namespace>{};
}

/// Generates the self-contained Dart library for all templates.
///
/// [templateSourceByPath] keys are `/`-separated paths relative to
/// [templateDirectory], such as `pages/admin/dashboard.html`.
/// [templateDirectory] only prefixes paths in diagnostics and source markers.
///
/// Throws a [Diagnostic] on invalid templates, naming conflicts or templates
/// that render each other in a cycle.
String generateDartLibrary({
  required Map<String, String> templateSourceByPath,
  required String className,
  String templateDirectory = '',
}) {
  final root = _buildNamespaceTree(
    templateSourceByPath.keys,
    className,
    templateDirectory,
  );
  final accessPathByTemplatePath = _accessPathByTemplatePath(root);
  final renderedFragmentsByTemplatePath = <String, List<RenderedFragment>>{};
  void compileNamespace(_Namespace namespace) {
    for (final MapEntry(key: methodName, value: templatePath)
        in namespace.templatePathByMethodName.entries) {
      final compiled = compileTemplate(
        templateSourceByPath[templatePath]!,
        displayTemplatePath(templateDirectory, templatePath),
        accessPathByTemplatePath: accessPathByTemplatePath,
      );
      namespace.compiledTemplateByMethodName[methodName] = compiled;
      renderedFragmentsByTemplatePath[templatePath] =
          compiled.renderedFragments;
    }
    namespace.namespaceByGetterName.values.forEach(compileNamespace);
  }

  compileNamespace(root);
  _rejectFragmentCycles(renderedFragmentsByTemplatePath, templateDirectory);

  final output = StringBuffer()
    ..writeln(generatedFileHeader)
    // The helpers go unused when no template writes a value.
    ..writeln('// ignore_for_file: type=lint, unused_element')
    ..writeln();
  _writeNamespace(output, root, isRoot: true);
  output.write(_fragmentSource);
  return output.toString();
}

/// Maps each of [templatePaths] to the Dart expression that calls it, such
/// as `Html.ui.label`, without compiling any template.
///
/// Throws a [Diagnostic] when they cannot all become distinct Dart members.
Map<String, String> templateAccessPaths({
  required Iterable<String> templatePaths,
  required String className,
  String templateDirectory = '',
}) => _accessPathByTemplatePath(
  _buildNamespaceTree(templatePaths, className, templateDirectory),
);

Map<String, String> _accessPathByTemplatePath(_Namespace root) {
  final accessPathByTemplatePath = <String, String>{};
  void collect(_Namespace namespace) {
    for (final MapEntry(key: methodName, value: templatePath)
        in namespace.templatePathByMethodName.entries) {
      accessPathByTemplatePath[templatePath] =
          '${namespace.accessPath}.$methodName';
    }
    namespace.namespaceByGetterName.values.forEach(collect);
  }

  collect(root);
  return accessPathByTemplatePath;
}

/// Throws a [Diagnostic] at the `<x-fragment>` that closes the first cycle
/// found, since rendering any template in it would never end.
void _rejectFragmentCycles(
  Map<String, List<RenderedFragment>> renderedFragmentsByTemplatePath,
  String templateDirectory,
) {
  final finishedTemplatePaths = <String>{};
  final templatePathsBeingVisited = <String>[];
  void visit(String templatePath) {
    if (finishedTemplatePaths.contains(templatePath)) return;
    templatePathsBeingVisited.add(templatePath);
    for (final rendered
        in renderedFragmentsByTemplatePath[templatePath] ?? const []) {
      final cycleStart = templatePathsBeingVisited.indexOf(
        rendered.templatePath,
      );
      if (cycleStart != -1) {
        final cycle = [
          ...templatePathsBeingVisited.sublist(cycleStart),
          rendered.templatePath,
        ].map((path) => '/$path').join(' -> ');
        throw Diagnostic(
          'templates cannot render themselves, directly or through other '
          'templates; this <x-fragment> closes the cycle $cycle',
          path: displayTemplatePath(templateDirectory, templatePath),
          line: rendered.line,
          column: rendered.column,
          lineText: rendered.lineText,
        );
      }
      visit(rendered.templatePath);
    }
    templatePathsBeingVisited.removeLast();
    finishedTemplatePaths.add(templatePath);
  }

  (renderedFragmentsByTemplatePath.keys.toList()..sort()).forEach(visit);
}

/// The path of a template as shown to users, such as
/// `fragments/pages/user.html`.
String displayTemplatePath(String templateDirectory, String templatePath) =>
    templateDirectory.isEmpty
    ? templatePath
    : '$templateDirectory/$templatePath';

_Namespace _buildNamespaceTree(
  Iterable<String> templatePaths,
  String className,
  String templateDirectory,
) {
  if (!_classNamePattern.hasMatch(className) || className == 'Fragment') {
    throw Diagnostic(
      'class name "$className" is invalid; use letters and digits, start '
      'with a letter, and do not use "Fragment"',
    );
  }
  final root = _Namespace(className, className);

  for (final templatePath in templatePaths.toList()..sort()) {
    final segments = templatePath.split('/');
    var namespace = root;
    for (var depth = 0; depth < segments.length - 1; depth++) {
      final directoryPath = displayTemplatePath(
        templateDirectory,
        '${segments.sublist(0, depth + 1).join('/')}/',
      );
      final getterName = _memberName(segments[depth], directoryPath);
      _claimMemberName(namespace, getterName, directoryPath);
      namespace = namespace.namespaceByGetterName.putIfAbsent(
        getterName,
        // Nested namespace classes stay private: only the root class is API.
        () => _Namespace(
          '${namespace == root ? '_' : ''}${namespace.className}\$$getterName',
          '${namespace.accessPath}.$getterName',
        ),
      );
    }
    final fileName = segments.last;
    final methodName = _memberName(
      fileName.substring(0, fileName.length - '.html'.length),
      displayTemplatePath(templateDirectory, templatePath),
    );
    _claimMemberName(
      namespace,
      methodName,
      displayTemplatePath(templateDirectory, templatePath),
    );
    namespace.templatePathByMethodName[methodName] = templatePath;
  }
  return root;
}

/// Records [memberName] in [namespace], rejecting names already taken by a
/// different file or directory.
void _claimMemberName(
  _Namespace namespace,
  String memberName,
  String sourcePath,
) {
  final existingSourcePath = namespace.sourcePathByMemberName[memberName];
  if (existingSourcePath != null && existingSourcePath != sourcePath) {
    throw Diagnostic(
      '$existingSourcePath and $sourcePath would both become '
      '${namespace.accessPath}.$memberName; rename one of them',
      path: sourcePath,
    );
  }
  namespace.sourcePathByMemberName[memberName] = sourcePath;
}

/// Converts a file or directory name such as `user-page` into `userPage`.
String _memberName(String name, String sourcePath) {
  final words = name.split(_wordSeparatorPattern).where((w) => w.isNotEmpty);
  final memberName = [
    for (final (index, word) in words.indexed)
      (index == 0 ? word[0].toLowerCase() : word[0].toUpperCase()) +
          word.substring(1),
  ].join();
  if (!_memberNamePattern.hasMatch(memberName) ||
      reservedDartNames.contains(memberName)) {
    throw Diagnostic(
      '"$name" cannot become a Dart name (it converts to "$memberName"); '
      'file and directory names must start with a letter and must not be '
      'Dart reserved words such as "class" or "switch"',
      path: sourcePath,
    );
  }
  return memberName;
}

void _writeNamespace(
  StringBuffer output,
  _Namespace namespace, {
  required bool isRoot,
}) {
  final memberPrefix = isRoot ? 'static ' : '';
  final members = [
    if (!isRoot) '  const ${namespace.className}();',
    for (final MapEntry(key: methodName, value: template)
        in namespace.compiledTemplateByMethodName.entries)
      '  ${memberPrefix}Fragment $methodName(${template.parameters}) =>\n'
          '      Fragment._((\$out) {\n'
          '    ${template.body.trimRight().replaceAll('\n', '\n    ')}\n'
          '  });',
    for (final MapEntry(key: getterName, value: child)
        in namespace.namespaceByGetterName.entries)
      isRoot
          ? '  static const $getterName = ${child.className}();'
          : '  ${child.className} get $getterName => const ${child.className}();',
  ];
  output
    ..writeln(
      '${isRoot ? 'abstract final' : 'final'} class ${namespace.className} {',
    )
    ..writeln(members.join('\n\n'))
    ..writeln('}')
    ..writeln();

  for (final child in namespace.namespaceByGetterName.values) {
    _writeNamespace(output, child, isRoot: false);
  }
}
