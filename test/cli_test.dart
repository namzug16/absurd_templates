import 'dart:io';

import 'package:absurd_templates/src/cli.dart';
import 'package:absurd_templates/src/vendor.dart';
import 'package:test/test.dart';

import '../tool/build_vendored_source.dart';

final _absScript = File('bin/abs.dart').absolute.path;
final _packageConfig = File('.dart_tool/package_config.json').absolute.path;

Future<ProcessResult> _runAbs(
  Directory projectDirectory, [
  List<String> arguments = const [],
  Map<String, String>? environment,
]) => Process.run(
  Platform.resolvedExecutable,
  ['--packages=$_packageConfig', _absScript, ...arguments],
  workingDirectory: projectDirectory.path,
  environment: environment,
);

void main() {
  late Directory projectDirectory;

  setUp(() async {
    projectDirectory = await Directory.systemTemp.createTemp('abs_cli_');
    addTearDown(() => projectDirectory.delete(recursive: true));
  });

  void writeProjectFile(String path, String contents) {
    File('${projectDirectory.path}/$path')
      ..createSync(recursive: true)
      ..writeAsStringSync(contents);
  }

  test('generates the configured output file', () async {
    writeProjectFile('abs.yaml', '''
input: fragments
output: lib/generated/html.dart
class: Html
''');
    writeProjectFile('fragments/layout/primary.html', '''
<x-props title="String" content="Fragment"></x-props>
<title>{{ title }}</title><main>{{ content }}</main>''');
    writeProjectFile('fragments/notes.txt', 'ignored');

    final result = await _runAbs(projectDirectory);

    expect(result.stderr, '');
    expect(result.exitCode, 0);
    expect(result.stdout, contains('generated lib/generated/html.dart'));
    final library = File(
      '${projectDirectory.path}/lib/generated/html.dart',
    ).readAsStringSync();
    expect(library, contains('abstract final class Html {'));
    expect(library, contains('static const layout = _Html\$layout();'));
  });

  test('leaves an unchanged output file alone', () async {
    writeProjectFile('abs.yaml', 'input: fragments\noutput: out.dart\n');
    writeProjectFile('fragments/header.html', '<header></header>');
    await _runAbs(projectDirectory);
    final outputFile = File('${projectDirectory.path}/out.dart');
    final firstModified = outputFile.lastModifiedSync();
    await Future<void>.delayed(const Duration(milliseconds: 1100));

    final result = await _runAbs(projectDirectory);

    expect(result.stdout, startsWith('abs: unchanged out.dart'));
    expect(outputFile.lastModifiedSync(), firstModified);
  });

  test('refuses to overwrite a file it did not generate', () async {
    writeProjectFile('abs.yaml', 'input: fragments\noutput: main.dart\n');
    writeProjectFile('fragments/header.html', '<header></header>');
    writeProjectFile('main.dart', 'void main() {}\n');

    final result = await _runAbs(projectDirectory);

    expect(result.exitCode, 1);
    expect(
      result.stderr,
      contains('main.dart already exists and was not generated by abs'),
    );
    expect(
      File('${projectDirectory.path}/main.dart').readAsStringSync(),
      'void main() {}\n',
    );
  });

  test('init creates a working abs.yaml and never overwrites it', () async {
    final initResult = await _runAbs(projectDirectory, ['init']);

    expect(initResult.exitCode, 0);
    expect(initResult.stdout, startsWith('abs: created abs.yaml'));
    final configFile = File('${projectDirectory.path}/abs.yaml');
    final config = configFile.readAsStringSync();
    expect(config, contains('input: fragments\n'));
    expect(config, contains('# class: Html\n'));

    writeProjectFile('fragments/header.html', '<header></header>');
    final generateResult = await _runAbs(projectDirectory);
    expect(generateResult.exitCode, 0);
    expect(
      File(
        '${projectDirectory.path}/lib/generated/html.dart',
      ).readAsStringSync(),
      contains('abstract final class Fragments {'),
    );

    configFile.writeAsStringSync('input: mine\n');
    final secondInitResult = await _runAbs(projectDirectory, ['init']);
    expect(secondInitResult.exitCode, 1);
    expect(secondInitResult.stderr, contains('abs.yaml already exists'));
    expect(configFile.readAsStringSync(), 'input: mine\n');
  });

  test('defaults the class name to Fragments', () async {
    writeProjectFile('abs.yaml', 'input: fragments\noutput: out.dart\n');
    writeProjectFile('fragments/header.html', '<header></header>');

    final result = await _runAbs(projectDirectory);

    expect(result.exitCode, 0);
    expect(
      File('${projectDirectory.path}/out.dart').readAsStringSync(),
      contains('abstract final class Fragments {'),
    );
  });

  test('accepts an input directory written as ./dir/', () async {
    writeProjectFile('abs.yaml', 'input: ./fragments/\noutput: out.dart\n');
    writeProjectFile('fragments/pages/home.html', '<p>home</p>');

    final result = await _runAbs(projectDirectory, [
      'check',
      'fragments/pages/home.html',
    ]);

    expect(result.stdout, 'abs check: 1 template OK\n');
    expect(result.exitCode, 0);
  });

  test('reads quoted values and comments in abs.yaml', () async {
    writeProjectFile('abs.yaml', """
# settings
input: "fragments"   # quoted
output: gen/a#b.dart  # the first # has no space before it
class: 'Html'
""");
    writeProjectFile('fragments/header.html', '<header></header>');

    final result = await _runAbs(projectDirectory);

    expect(result.stderr, '');
    expect(
      File('${projectDirectory.path}/gen/a#b.dart').readAsStringSync(),
      contains('abstract final class Html'),
    );
  });

  group('rejects abs.yaml with', () {
    final messageByConfig = {
      'input: fragments\n  nested: x\noutput: o.dart\n': 'abs.yaml:2:1',
      'input: [fragments]\noutput: o.dart\n': 'expected a "key: value" line',
      'input: fragments\ninput: other\noutput: o.dart\n':
          '"input" is set twice',
      'input: fragments\noutput: o.dart\nclas: Html\n': 'unknown key "clas"',
      'input:fragments\noutput: o.dart\n': 'expected a "key: value" line',
    };
    for (final MapEntry(key: config, value: message)
        in messageByConfig.entries) {
      test(config.split('\n').first, () async {
        writeProjectFile('abs.yaml', config);
        writeProjectFile('fragments/header.html', '<header></header>');

        final result = await _runAbs(projectDirectory);

        expect(result.exitCode, 1);
        expect(result.stderr, contains(message));
      });
    }
  });

  test('rejects an empty class instead of using the default', () async {
    writeProjectFile('abs.yaml', 'input: fragments\noutput: o.dart\nclass:\n');
    writeProjectFile('fragments/header.html', '<header></header>');

    final result = await _runAbs(projectDirectory);

    expect(result.exitCode, 1);
    expect(result.stderr, contains('"class" must be a non-empty string'));
    expect(result.stderr, contains('abs.yaml:3:'));
  });

  test('reports errors and exits with 1', () async {
    writeProjectFile('abs.yaml', 'input: fragments\n');

    final result = await _runAbs(projectDirectory);

    expect(result.exitCode, 1);
    expect(result.stderr, '''
error: "output" is required (see "abs help")
  --> abs.yaml:1:1
  |
1 | input: fragments
  | ^
''');
  });

  test('committed examples/generated/html.dart is up to date', () async {
    final generatedFile = File('examples/generated/html.dart');
    final committedLibrary = generatedFile.readAsStringSync();

    final result = await _runAbs(Directory('examples'));

    expect(result.exitCode, 0);
    expect(
      generatedFile.readAsStringSync(),
      committedLibrary,
      reason: 'run abs in examples/ and commit the result',
    );
  });

  group('abs check', () {
    setUp(() {
      writeProjectFile('abs.yaml', 'input: fragments\noutput: out.dart\n');
      writeProjectFile(
        'fragments/ok.html',
        '<x-props name="String"></x-props>{{ name }}',
      );
    });

    test('maps Dart errors back to the template line', () async {
      writeProjectFile('fragments/broken.html', '''
<x-props
  name="Strng"
  users="List<({String name})>"
></x-props>
<x-for in="users" as="user">
  <li>{{ user.nmae }}</li>
</x-for>
''');

      final result = await _runAbs(projectDirectory, ['check']);

      expect(result.exitCode, 1);
      expect(
        result.stdout,
        contains('''
error: Undefined class 'Strng'.
  --> fragments/broken.html:2:9
  |
2 |   name="Strng"
  |         ^
'''),
      );
      expect(
        result.stdout,
        contains('''
  --> fragments/broken.html:6:10
  |
6 |   <li>{{ user.nmae }}</li>
  |          ^
'''),
      );
      expect(
        result.stdout,
        endsWith('2 errors and 0 warnings in 2 templates\n'),
      );
      expect(File('${projectDirectory.path}/out.dart').existsSync(), isFalse);
    });

    test('maps <x-fragment> prop errors to their attributes', () async {
      writeProjectFile(
        'fragments/ui/badge.html',
        '<x-props label="String" count="int"></x-props>{{ label }}{{ count }}',
      );
      writeProjectFile('fragments/page.html', '''
<x-fragment _="/ui/badge.html" label="Users" count="3" />
''');
      writeProjectFile(
        'fragments/undeclared.html',
        '<x-fragment _="/ui/badge.html" count="{{ missing }}" />',
      );
      writeProjectFile('fragments/other.html', '''
<x-fragment _="/ok.html"
  name="Ada"
  colour="red" />
<x-fragment _="/ok.html" />
''');
      writeProjectFile('fragments/slotted.html', '''
<x-props count="int"></x-props>
<x-fragment _="/ui/badge.html" count="{{ count }}">
  <x-slot name="label">Users</x-slot>
</x-fragment>
''');

      final result = await _runAbs(projectDirectory, ['check']);

      expect(result.exitCode, 1);
      expect(
        result.stdout,
        contains('''
error: The argument type 'String' can't be assigned to the parameter type 'int'. 
  --> fragments/page.html:1:53
'''),
      );
      expect(result.stdout, contains('"missing" is not declared'));
      expect(
        result.stdout,
        contains('''
error: The named parameter 'colour' isn't defined.
  --> fragments/other.html:3:11
'''),
      );
      expect(
        result.stdout,
        contains('''
error: The named parameter 'name' is required, but there's no corresponding argument.
  --> fragments/other.html:4:1
'''),
      );
      expect(
        result.stdout,
        contains('''
error: The argument type 'Fragment' can't be assigned to the parameter type 'String'. 
  --> fragments/slotted.html:3:17
'''),
      );
    });

    test('analyzes the templates a checked file renders', () async {
      writeProjectFile(
        'fragments/page.html',
        '<x-fragment _="/ok.html" name="Ada" />',
      );

      final result = await _runAbs(projectDirectory, [
        'check',
        'fragments/page.html',
      ]);

      expect(result.stdout, 'abs check: 1 template OK\n');
      expect(result.exitCode, 0);
    });

    test('rejects templates that render each other', () async {
      writeProjectFile('fragments/a.html', '<x-fragment _="/b.html" />');
      writeProjectFile('fragments/b.html', '<x-fragment _="/a.html" />');

      final result = await _runAbs(projectDirectory, [
        'check',
        'fragments/a.html',
      ]);

      expect(result.exitCode, 1);
      expect(
        result.stdout,
        contains('closes the cycle /a.html -> /b.html -> /a.html'),
      );
    });

    test('reports naming conflicts next to a missing template', () async {
      writeProjectFile('fragments/a.html', '<x-fragment _="/missing.html" />');
      writeProjectFile('fragments/user-page.html', '');
      writeProjectFile('fragments/user_page.html', '');

      final result = await _runAbs(projectDirectory, ['check']);

      expect(result.exitCode, 1);
      expect(result.stdout, contains('would both become Fragments.userPage'));
    });

    test('checks only the given files, once each', () async {
      writeProjectFile('fragments/broken.html', '{{ missing }}');

      final result = await _runAbs(projectDirectory, [
        'check',
        'fragments/ok.html',
        './fragments/ok.html',
      ]);

      expect(result.stdout, 'abs check: 1 template OK\n');
      expect(result.exitCode, 0);
    });

    test('passes a template that writes no values', () async {
      writeProjectFile('fragments/static.html', '<p>static</p>');

      final result = await _runAbs(projectDirectory, [
        'check',
        'fragments/static.html',
      ]);

      expect(result.stdout, 'abs check: 1 template OK\n');
      expect(result.exitCode, 0);
    });

    test('fails when dart analyze cannot run', () async {
      writeProjectFile(
        'fake-bin/dart',
        '#!/bin/sh\necho "analyzer crashed" >&2\nexit 64\n',
      );
      Process.runSync('chmod', [
        '+x',
        '${projectDirectory.path}/fake-bin/dart',
      ]);

      final result = await _runAbs(
        projectDirectory,
        ['check'],
        {
          'PATH':
              '${projectDirectory.path}/fake-bin:${Platform.environment['PATH']}',
        },
      );

      expect(result.exitCode, 1);
      expect(
        result.stdout,
        contains(
          '"dart analyze" failed with exit code 64, so Dart errors were not '
          'checked:\nanalyzer crashed',
        ),
      );
    }, testOn: '!windows');

    test('rejects files outside the input directory', () async {
      final result = await _runAbs(projectDirectory, ['check', 'other.html']);

      expect(result.exitCode, 1);
      expect(
        result.stderr,
        contains('"other.html" is not inside the input directory "fragments"'),
      );
    });
  });

  test('lib/src/vendored_source.dart is up to date', () {
    expect(
      File(vendoredSourceFile).readAsStringSync(),
      buildVendoredSourceFile(),
      reason: 'run "dart run tool/build_vendored_source.dart"',
    );
  });

  test('absVersion matches pubspec.yaml', () {
    expect(
      File('pubspec.yaml').readAsStringSync(),
      contains('\nversion: $absVersion\n'),
    );
  });

  group('abs vendor', () {
    late File vendoredFile;

    setUp(() {
      writeProjectFile('abs.yaml', 'input: fragments\noutput: out.dart\n');
      writeProjectFile(
        'fragments/header.html',
        '<x-props title="String"></x-props><h1>{{ title }}</h1>',
      );
      vendoredFile = File('${projectDirectory.path}/tool/abs.dart');
    });

    test('writes a copy that works without abs or any package', () async {
      final vendorResult = await _runAbs(projectDirectory, ['vendor']);
      expect(
        vendorResult.stdout,
        startsWith('abs: vendored abs $absVersion into tool/abs.dart'),
      );

      final copyResult = await Process.run(Platform.resolvedExecutable, [
        'tool/abs.dart',
      ], workingDirectory: projectDirectory.path);
      expect(copyResult.stderr, '');
      expect(copyResult.exitCode, 0);

      // The installed abs would write exactly what the copy wrote.
      final installedResult = await _runAbs(projectDirectory);
      expect(installedResult.stdout, startsWith('abs: unchanged out.dart'));

      final secondVendorResult = await _runAbs(projectDirectory, ['vendor']);
      expect(
        secondVendorResult.stdout,
        'abs: tool/abs.dart is already abs $absVersion\n',
      );
    });

    test('updates a copy from an older abs', () async {
      writeProjectFile(
        'tool/abs.dart',
        vendoredFileContent('tool/abs.dart', version: '0.0.1'),
      );

      final result = await _runAbs(projectDirectory, ['vendor']);

      expect(
        result.stdout,
        'abs: updated tool/abs.dart from abs 0.0.1 to $absVersion\n',
      );
      expect(
        vendoredFile.readAsStringSync(),
        vendoredFileContent('tool/abs.dart'),
      );
    });

    final messageByExistingFile = {
      'void main() {}\n': 'was not written by "abs vendor"',
      '${vendoredFileContent('tool/abs.dart')}// my change\n': 'was edited',
      vendoredFileContent('tool/abs.dart', version: '99.0.0'):
          'newer than this abs',
    };
    for (final MapEntry(key: existingContent, value: message)
        in messageByExistingFile.entries) {
      test('leaves the file alone: $message', () async {
        writeProjectFile('tool/abs.dart', existingContent);

        final result = await _runAbs(projectDirectory, ['vendor']);

        expect(result.exitCode, 1);
        expect(result.stderr, contains(message));
        expect(vendoredFile.readAsStringSync(), existingContent);
      });
    }
  });
}
