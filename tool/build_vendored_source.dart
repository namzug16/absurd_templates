import 'dart:convert';
import 'dart:io';

/// Regenerates lib/src/vendored_source.dart, which `abs vendor` copies into
/// projects. Run it from the package root after changing lib/src:
///
///     dart run tool/build_vendored_source.dart
void main() {
  File(vendoredSourceFile).writeAsStringSync(buildVendoredSourceFile());
  stdout.writeln('wrote $vendoredSourceFile');
}

const vendoredSourceFile = 'lib/src/vendored_source.dart';

/// Files merged into the vendored copy, in order. Everything else in
/// lib/src (the vendor command and its embedded source) stays out.
const _bundledFiles = [
  'diagnostic.dart',
  'template.dart',
  'generator.dart',
  'check.dart',
  'cli.dart',
];

final _importPattern = RegExp(r"^import '([^']+)';$");

/// The content of [vendoredSourceFile]: lib/src merged into one library and
/// embedded as a string constant.
String buildVendoredSourceFile() {
  final sdkImports = <String>{};
  final sections = <String>[];
  for (final fileName in _bundledFiles) {
    final linesWithoutImports = <String>[];
    for (final line in File('lib/src/$fileName').readAsLinesSync()) {
      final import = _importPattern.firstMatch(line)?[1];
      if (import == null) {
        linesWithoutImports.add(line);
      } else if (import.startsWith('dart:')) {
        sdkImports.add(line);
      } else if (import.contains(':') || import.contains('/')) {
        throw StateError(
          'lib/src/$fileName imports "$import"; the vendored copy can only '
          'use dart: libraries and the files in lib/src',
        );
      }
    }
    sections.add(
      '// lib/src/$fileName\n${linesWithoutImports.join('\n').trim()}',
    );
  }
  final source = [
    (sdkImports.toList()..sort()).join('\n'),
    'Future<void> main(List<String> arguments) => runAbs(arguments);',
    ...sections,
  ].join('\n\n');
  final stringLiteralLines = [
    for (final line in source.split('\n'))
      // A JSON string is a Dart string once "$" cannot interpolate.
      '    ${jsonEncode('$line\n').replaceAll(r'$', r'\$')}',
  ];
  return '// GENERATED by tool/build_vendored_source.dart from lib/src. '
      'DO NOT EDIT.\n'
      '\n'
      '/// The whole abs tool as one Dart library, without the vendor command.\n'
      'const vendoredSource =\n'
      '${stringLiteralLines.join('\n')};\n';
}
